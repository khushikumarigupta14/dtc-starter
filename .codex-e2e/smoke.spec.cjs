const { test, expect } = require("playwright/test")
const path = require("path")

const shot = (name) => path.join(__dirname, "screenshots", name)

test("guest completes COD checkout then requests similar artwork", async ({ page }) => {
  const findings = []
  page.on("pageerror", (error) => findings.push({ type: "pageerror", message: error.message }))
  page.on("response", (response) => {
    if (response.status() >= 500) findings.push({ type: "http", status: response.status(), url: response.url() })
  })

  await page.goto("/in/products/e2e-sunlit-study")
  await expect(page.getByTestId("product-title")).toHaveText("Sunlit Courtyard Study")
  await expect(page.getByTestId("add-product-button")).toHaveText("Add to cart", { timeout: 15_000 })
  await page.screenshot({ path: shot("01-product.png"), fullPage: true })

  await page.getByTestId("add-product-button").click()
  await page.waitForLoadState("networkidle")
  await page.waitForTimeout(1_000)
  await page.goto("/in/cart")
  await expect(page.getByTestId("cart-container")).toBeVisible()
  await expect(page.getByTestId("product-title")).toHaveText("Sunlit Courtyard Study")
  await expect(page.getByRole("link", { name: "Cart (1)", exact: true })).toBeVisible({ timeout: 15_000 })
  await page.screenshot({ path: shot("02-cart.png"), fullPage: true })

  await page.getByTestId("checkout-button").click()
  await expect(page).toHaveURL(/\/in\/checkout\?step=address/)
  await expect(page.getByTestId("store-link")).toHaveText("Colourpalet")
  await page.getByTestId("shipping-first-name-input").fill("E2E")
  await page.getByTestId("shipping-last-name-input").fill("Customer")
  await page.getByTestId("shipping-address-input").fill("12 Test Garden Road")
  await page.getByTestId("shipping-postal-code-input").fill("110001")
  await page.getByTestId("shipping-city-input").fill("New Delhi")
  await page.getByTestId("shipping-country-select").selectOption("in")
  await page.getByTestId("shipping-province-input").fill("Delhi")
  await page.getByTestId("shipping-email-input").fill("e2e.customer@example.com")
  await page.getByTestId("shipping-phone-input").fill("9999999999")
  await page.screenshot({ path: shot("03-address.png"), fullPage: true })
  await page.getByTestId("submit-address-button").click()

  await expect(page).toHaveURL(/step=delivery/, { timeout: 15_000 })
  const deliveryOptions = page.getByTestId("delivery-option-radio")
  await expect(deliveryOptions.first()).toBeVisible()
  await deliveryOptions.first().click()
  await expect(page.getByTestId("submit-delivery-option-button")).toBeEnabled()
  await page.screenshot({ path: shot("04-delivery.png"), fullPage: true })
  await page.getByTestId("submit-delivery-option-button").click()

  await expect(page).toHaveURL(/step=payment/)
  await page.getByText("Cash on Delivery", { exact: true }).click()
  await expect(page.getByText("Payment is due when your artwork is delivered.")).toBeVisible()
  await page.screenshot({ path: shot("05-payment.png"), fullPage: true })
  await page.getByTestId("submit-payment-button").click()

  await expect(page).toHaveURL(/step=review/)
  await expect(page.getByText(/Medusa Store/)).toHaveCount(0)
  await expect(page.getByTestId("submit-order-button")).toBeEnabled()
  await page.screenshot({ path: shot("06-review.png"), fullPage: true })
  await page.getByTestId("submit-order-button").click()

  await expect(page.getByTestId("order-complete-container")).toBeVisible({ timeout: 30_000 })
  await expect(page.getByTestId("payment-method")).toHaveText("Cash on Delivery")
  const orderId = await page.getByTestId("order-id").innerText()
  await page.screenshot({ path: shot("07-confirmation.png"), fullPage: true })

  await page.goto("/in/products/e2e-sunlit-study")
  const productAction = page.getByTestId("product-container").getByTestId("add-product-button")
  await expect(productAction).toHaveText("SOLD", { timeout: 15_000 })
  await page.getByRole("link", { name: "Request similar artwork" }).click()
  await expect(page).toHaveURL(/\/in\/custom-artwork\?inspired_by=prod_01M3HG1WXV0R1FM066F45D7YPT/)
  await expect(page.locator('input[name="inspired_by_product_id"]')).toHaveValue("prod_01M3HG1WXV0R1FM066F45D7YPT")
  await page.getByLabel("Full name").fill("E2E Customer")
  await page.getByLabel("Email").fill("e2e.customer@example.com")
  await page.getByLabel("Artwork type").selectOption({ label: "Painting" })
  await page.getByLabel("Preferred medium").selectOption({ label: "Watercolour" })
  await page.getByLabel("Tell us about the artwork").fill("Please create a similar sunlit courtyard study for this automated acceptance test.")
  await page.screenshot({ path: shot("08-custom-request.png"), fullPage: true })
  await page.getByRole("button", { name: "Send artwork request" }).click()
  await expect(page.getByRole("heading", { name: "Request received" })).toBeVisible()
  await page.screenshot({ path: shot("09-request-received.png"), fullPage: true })

  console.log("E2E_RESULT", JSON.stringify({ orderId, findings }))
  expect(findings).toEqual([])
})
